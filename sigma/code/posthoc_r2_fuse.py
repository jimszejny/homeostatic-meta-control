"""POST HOC (added in revision after review R2, finding 2). Not pre-specified.

Proposition prop:sigma-fuse assumes that self-evidence occurs only on steps whose COMMITTED mode is
GUARD (as in e4_lockin.py). R2 reports that if self-evidence is generated by the EXECUTED mode
(the mode committed L=3 steps earlier), the count bound T_dw fails. This script reruns the E4
Monte Carlo of e4_lockin.py (same controller, same fuse logic, same seed and stream layout, common
random numbers across rows) for the fuse T_dw=100, T_pr=20 under three evidence models:
  'committed'      : e_t only if the mode committed at t is GUARD   (the model of the paper; control)
  'executed'       : e_t only if the mode executed at t (committed at t-3) is GUARD
  'executed_mask'  : as 'executed', and sigma ignores ALL input (u_t=0) for L=3 steps after every
                     release of the latch and every fuse trip (the remedy R2 proposes)
and reports, per psi, the maximum number of committed GUARD steps after the last real announcement
(max over all announcement-free gaps, as in e4_lockin.py), the maximum span, J and the GUARD fraction.
Writes ../results/posthoc_r2_fuse.json.
"""
import json, time
import numpy as np
from chain import REG, Qmat, impact_prob_given_z, kG, stationary_z

t0 = time.time()
base = dict(REG)
e2 = json.load(open('../results/e2.json'))
best = e2['by_csw']['0.0']['summary']['best_sigma_literal']
LAM = float(e2['by_csw']['0.0']['summary']['best_lambda_literal'])
TH_ON, TH_OFF = float(best['theta_on']), float(best['theta_off'])
L = 3
RHOS = [0.0, 0.05, 0.1, 0.2, 0.3, 0.5]
MODES = ['committed', 'executed', 'executed_mask']
TMAX, PWIN = 100, 20
CH = 64
T, BURN = 60000, 4000
cfg = [(r, m) for m in MODES for r in RHOS]
nK = len(cfg); nC = nK * CH
rho = np.repeat([c[0] for c in cfg], CH)
mode = np.repeat([MODES.index(c[1]) for c in cfg], CH)

rng = np.random.default_rng(404)
ps = np.array([base['p0'], base['p1']])
imp = impact_prob_given_z(base)
k = kG(base['G'], base['h'])
wz = 1 - imp * k
pz = stationary_z(base['q01'], base['q10'])
tile = lambda x: np.tile(x, nK)
z = tile(rng.random(CH) < pz[1]).astype(np.int8)
sig = np.zeros(nC); l = np.zeros(nC, np.int8); dwell = np.zeros(nC, np.int64); probe = np.zeros(nC, np.int64)
hist = np.zeros((L, nC), np.int8)        # hist[0] = mode committed at t-1, ..., hist[L-1] = at t-L
mask = np.zeros(nC, np.int64)
last_a = np.full(nC, -10**9, np.int64)
acc_r = np.zeros(nC); acc_g = np.zeros(nC); n = 0
max_d = np.zeros(nC, np.int64)
cnt = np.zeros(nC, np.int64); max_cnt = np.zeros(nC, np.int64)
for t in range(T):
    lprev = l.copy()
    inprobe = probe > 0
    lat = np.where(sig >= TH_ON - 1e-12, 1, np.where(sig < TH_OFF - 1e-12, 0, lprev))
    lnew = np.where(inprobe, 0, lat).astype(np.int8)
    probe = np.where(inprobe, probe - 1, probe)
    dwell = np.where(lnew == 1, dwell + 1, 0)
    trip = (lnew == 1) & (dwell > TMAX)
    lnew = np.where(trip, 0, lnew).astype(np.int8)
    sig = np.where(trip, 0.0, sig)
    probe = np.where(trip, PWIN - 1, probe)
    dwell = np.where(trip, 0, dwell)
    release = (lprev == 1) & (lnew == 0) & ~trip
    l = lnew
    executed = hist[L - 1]                 # mode committed at t-L executes at t
    a = tile(rng.random(CH)) < ps[z]
    ev = tile(rng.random(CH)) < rho        # same draw layout as e4_lockin.py
    gate = np.where(mode == 0, l == 1, executed == 1)
    e = ev & gate
    u = a | e
    # mask: sigma ignores all input for L steps after a release or a trip (executed_mask only)
    mask = np.where((mode == 2) & (release | trip), L, mask)
    u = np.where(mask > 0, False, u)
    mask = np.maximum(mask - 1, 0)
    if t >= BURN:
        acc_r += np.where(l == 1, base['r_g'], wz[z]); acc_g += l; n += 1
        d = np.where(l == 1, t - last_a, 0)
        max_d = np.maximum(max_d, d)
        cnt = cnt + (l == 1)
        max_cnt = np.maximum(max_cnt, cnt)
    cnt = np.where(a, 0, cnt)
    last_a = np.where(a, t, last_a)
    sig = (1 - LAM) * sig + LAM * u
    hist = np.roll(hist, 1, axis=0); hist[0] = l
    U = tile(rng.random(CH))
    z = np.where(z == 0, (U < base['q01']).astype(np.int8), (U >= base['q10']).astype(np.int8))

rows = []
for ci, (r, m) in enumerate(cfg):
    sl = slice(ci * CH, (ci + 1) * CH)
    J = acc_r[sl] / n; G = acc_g[sl] / n
    rows.append(dict(rho=r, evidence=m, T_dw=TMAX, T_pr=PWIN,
                     J=float(J.mean()), J_se=float(J.std(ddof=1) / np.sqrt(CH)),
                     guard_frac=float(G.mean()), guard_frac_se=float(G.std(ddof=1) / np.sqrt(CH)),
                     max_guard_count_after_last_real_announcement=int(max_cnt[sl].max()),
                     max_guard_span_after_last_real_announcement=int(max_d[sl].max()),
                     count_bound_holds=bool(max_cnt[sl].max() <= TMAX),
                     span_bound_holds=bool(max_d[sl].max() <= TMAX + PWIN - 1)))
    print(f"{m:14s} psi={r:<5} J={rows[-1]['J']:.5f}±{rows[-1]['J_se']:.5f} guard={rows[-1]['guard_frac']:.4f} "
          f"max count={rows[-1]['max_guard_count_after_last_real_announcement']} "
          f"max span={rows[-1]['max_guard_span_after_last_real_announcement']}", flush=True)
out = dict(note='POST HOC, added in revision after review R2 (finding 2); not pre-specified',
           controller=dict(lam=LAM, theta_on=TH_ON, theta_off=TH_OFF), fuse=dict(T_dw=TMAX, T_pr=PWIN), L=L,
           mc=dict(chains=CH, T=T, burn=BURN, seed=404), rows=rows, wall_s=time.time() - t0)
# FIX2 (review R6, finding 10): paired differences on the same streams, per psi (added output only)
paired = []
for r in RHOS:
    i0 = cfg.index((r, 'committed')); i1 = cfg.index((r, 'executed')); i2 = cfg.index((r, 'executed_mask'))
    a = acc_r[i0*CH:(i0+1)*CH] / n; c = acc_r[i1*CH:(i1+1)*CH] / n; b = acc_r[i2*CH:(i2+1)*CH] / n
    paired.append(dict(rho=r, mask_minus_committed=float((b-a).mean()),
                       mask_minus_committed_se=float((b-a).std(ddof=1) / np.sqrt(CH)),
                       executed_minus_committed=float((c-a).mean()),
                       executed_minus_committed_se=float((c-a).std(ddof=1) / np.sqrt(CH))))
    print(f"paired psi={r}: mask-committed {paired[-1]['mask_minus_committed']:.6f} se {paired[-1]['mask_minus_committed_se']:.6f}", flush=True)
out['paired_differences_FIX2'] = paired
json.dump(out, open('../results/posthoc_r2_fuse.json', 'w'), indent=1, default=float)
print(f'done {time.time()-t0:.1f}s')
